package custodyv2

import (
	"bytes"
	"crypto/ed25519"
	"errors"

	"github.com/outcomemesh/outcomemesh/core/codec"
	"github.com/outcomemesh/outcomemesh/core/types"
	"github.com/outcomemesh/outcomemesh/node/transport"
)

// Delivery deliberately has a smaller limit than the complete operator-channel
// binding. Histories exceeding it remain on that explicit channel until a
// separately reviewed chunking protocol exists.
const MaximumAdmissionDeliveryBytes = 8 << 20
const MaximumAdmissionDeliveryEnrollmentBytes = 10 + 7*types.HashSize + 1 + ed25519.PublicKeySize
const AdmissionDeliveryReceiptBytes = 10 + 5*types.HashSize + 1 + ed25519.SignatureSize

var ErrAdmissionDelivery = errors.New("invalid pinned custody V2 admission proof delivery")

type AdmissionDeliveryRole uint8

const (
	AdmissionDeliveryAuthority AdmissionDeliveryRole = 1
	AdmissionDeliveryTarget    AdmissionDeliveryRole = 2
)

// AdmissionDeliveryEnrollment is a public, independently pinned receiver
// descriptor. PlacementID commits salted local placement without publishing
// filesystem paths. Nonce and PlacementID must be generated by enrollment, not
// inferred from a received request. ReceiptPublicKey is the signed role key;
// RecipientPeerID additionally pins the concrete authenticated channel.
type AdmissionDeliveryEnrollment struct {
	Version                                                      uint16
	ContextID, ScopeID, BindingID, SenderPeerID, RecipientPeerID types.Hash
	PlacementID, Nonce                                           types.Hash
	Role                                                         AdmissionDeliveryRole
	ReceiptPublicKey                                             [32]byte
}

func (e AdmissionDeliveryEnrollment) CanonicalBytes() ([]byte, error) {
	if e.Version != Version2 || e.ContextID.IsZero() || e.ScopeID.IsZero() || e.BindingID.IsZero() || e.SenderPeerID.IsZero() || e.RecipientPeerID.IsZero() || e.SenderPeerID == e.RecipientPeerID || e.PlacementID.IsZero() || e.Nonce.IsZero() || types.Hash(e.ReceiptPublicKey).IsZero() || (e.Role != AdmissionDeliveryAuthority && e.Role != AdmissionDeliveryTarget) {
		return nil, ErrAdmissionDelivery
	}
	out := codec.NewEncoder(MaximumAdmissionDeliveryEnrollmentBytes)
	out.Fixed([]byte("OMCVDEN2"))
	out.U16(e.Version)
	for _, id := range []types.Hash{e.ContextID, e.ScopeID, e.BindingID, e.SenderPeerID, e.RecipientPeerID, e.PlacementID, e.Nonce} {
		out.Fixed(id[:])
	}
	out.U8(uint8(e.Role))
	out.Fixed(e.ReceiptPublicKey[:])
	return out.Bytes(), nil
}

func DecodeAdmissionDeliveryEnrollment(raw []byte) (AdmissionDeliveryEnrollment, error) {
	var e AdmissionDeliveryEnrollment
	if len(raw) != MaximumAdmissionDeliveryEnrollmentBytes {
		return e, ErrAdmissionDelivery
	}
	d := codec.NewDecoder(raw)
	if !magic(d, "OMCVDEN2") {
		return e, ErrAdmissionDelivery
	}
	e.Version, _ = d.U16()
	for _, id := range []*types.Hash{&e.ContextID, &e.ScopeID, &e.BindingID, &e.SenderPeerID, &e.RecipientPeerID, &e.PlacementID, &e.Nonce} {
		fixed(d, id[:])
	}
	role, _ := d.U8()
	e.Role = AdmissionDeliveryRole(role)
	fixed(d, e.ReceiptPublicKey[:])
	again, err := e.CanonicalBytes()
	if err != nil || d.Finish() != nil || !bytes.Equal(again, raw) {
		return AdmissionDeliveryEnrollment{}, ErrAdmissionDelivery
	}
	return e, nil
}

func (e AdmissionDeliveryEnrollment) ID() (types.Hash, error) {
	raw, err := e.CanonicalBytes()
	if err != nil {
		return types.Hash{}, err
	}
	return types.DomainHash("OMESH/custody/v2/required/admission-delivery/enrollment/id", raw), nil
}

func (e AdmissionDeliveryEnrollment) Verify(c Context) error {
	if _, err := e.CanonicalBytes(); err != nil {
		return err
	}
	if c.Assignment.Policy.Version != PolicyVersionAdmission {
		return ErrAdmissionDelivery
	}
	cid, err := c.ID()
	if err != nil || cid != e.ContextID {
		return errors.Join(ErrAdmissionDelivery, err)
	}
	scope, err := c.Scope()
	if err != nil {
		return errors.Join(ErrAdmissionDelivery, err)
	}
	sid, err := scope.ID()
	if err != nil || sid != e.ScopeID {
		return errors.Join(ErrAdmissionDelivery, err)
	}
	sender, err := transport.PeerIDFromPublicKey(c.Plan.ClientTransportPublicKey[:])
	if err != nil || sender != e.SenderPeerID {
		return errors.Join(ErrAdmissionDelivery, err)
	}
	if e.Role == AdmissionDeliveryAuthority {
		// An A transport identity is not signed into the assignment. This
		// independently pinned descriptor selects it; it must not be inferred
		// from a route or substituted by an incoming request.
		if e.ReceiptPublicKey != c.Assignment.Base.AuthorityPublicKey {
			return ErrAdmissionDelivery
		}
		return nil
	}
	recipient, err := transport.PeerIDFromPublicKey(c.Assignment.Base.RemoteTransportPublicKey[:])
	if err != nil || recipient != e.RecipientPeerID || e.ReceiptPublicKey != c.Assignment.Base.RemoteControlPublicKey {
		return errors.Join(ErrAdmissionDelivery, err)
	}
	return nil
}

// AdmissionDelivery transfers one exact public proof. Its validation neither
// queries the current admission head nor grants any physical custody effect.
type AdmissionDelivery struct {
	Version    uint16
	Enrollment AdmissionDeliveryEnrollment
	Context    Context
	Binding    AdmissionBinding
}

func deliveryFieldBytes(n int) int {
	header := 1
	for x := n; x >= 128; x >>= 7 {
		header++
	}
	return header + n
}

func deliveryBindingBytes(b AdmissionBinding, limit int) ([]byte, error) {
	// Preflight each bounded certificate before building the complete binding.
	// This prevents the 512 MiB operator format from allocating a large packet
	// merely to discover that the smaller delivery channel cannot carry it.
	g, err := b.Genesis.CanonicalBytes()
	if err != nil || len(b.Chain) == 0 || uint64(len(b.Chain)) > MaxAdmissionEntries(b.Genesis) {
		return nil, errors.Join(ErrAdmissionDelivery, err)
	}
	size := 14 + deliveryFieldBytes(len(g))
	if size > limit {
		return nil, ErrAdmissionDelivery
	}
	for _, q := range b.Chain {
		raw, err := q.CanonicalBytes()
		if err != nil {
			return nil, errors.Join(ErrAdmissionDelivery, err)
		}
		size += deliveryFieldBytes(len(raw))
		if size > limit {
			return nil, ErrAdmissionDelivery
		}
	}
	return b.CanonicalBytes()
}

func (d AdmissionDelivery) CanonicalBytes() ([]byte, error) {
	if d.Version != Version2 {
		return nil, ErrAdmissionDelivery
	}
	enrollment, err := d.Enrollment.CanonicalBytes()
	if err != nil {
		return nil, err
	}
	c, err := d.Context.CanonicalBytes()
	if err != nil {
		return nil, errors.Join(ErrAdmissionDelivery, err)
	}
	// Reserve at least the binding field's length prefix now and enforce its
	// complete canonical length below. The preflight allocation stays bounded.
	remaining := MaximumAdmissionDeliveryBytes - 10 - deliveryFieldBytes(len(enrollment)) - deliveryFieldBytes(len(c)) - 1
	if remaining <= 0 {
		return nil, ErrAdmissionDelivery
	}
	b, err := deliveryBindingBytes(d.Binding, remaining)
	if err != nil {
		return nil, err
	}
	if err := d.Enrollment.Verify(d.Context); err != nil {
		return nil, err
	}
	if err := d.Binding.Verify(d.Context); err != nil {
		return nil, errors.Join(ErrAdmissionDelivery, err)
	}
	bid := types.DomainHash("OMESH/custody/v2/required/admission-binding/id", b)
	if bid != d.Enrollment.BindingID {
		return nil, ErrAdmissionDelivery
	}
	out := codec.NewEncoder(10 + len(enrollment) + len(c) + len(b) + 30)
	out.Fixed([]byte("OMCVDLV2"))
	out.U16(d.Version)
	out.BytesField(enrollment)
	out.BytesField(c)
	out.BytesField(b)
	raw := out.Bytes()
	if len(raw) > MaximumAdmissionDeliveryBytes {
		return nil, ErrAdmissionDelivery
	}
	return raw, nil
}

func (d AdmissionDelivery) Validate() error {
	_, err := d.CanonicalBytes()
	return err
}

func (d AdmissionDelivery) ID() (types.Hash, error) {
	raw, err := d.CanonicalBytes()
	if err != nil {
		return types.Hash{}, err
	}
	return types.DomainHash("OMESH/custody/v2/required/admission-delivery/id", raw), nil
}

func DecodeAdmissionDelivery(raw []byte) (AdmissionDelivery, error) {
	var value AdmissionDelivery
	if len(raw) > MaximumAdmissionDeliveryBytes {
		return value, ErrAdmissionDelivery
	}
	d := codec.NewDecoder(raw)
	if !magic(d, "OMCVDLV2") {
		return value, ErrAdmissionDelivery
	}
	value.Version, _ = d.U16()
	e, err := d.BytesField(MaximumAdmissionDeliveryEnrollmentBytes)
	if err != nil {
		return value, err
	}
	value.Enrollment, err = DecodeAdmissionDeliveryEnrollment(e)
	if err != nil {
		return value, err
	}
	c, err := d.BytesField(MaximumContextBytes)
	if err != nil {
		return value, err
	}
	value.Context, err = DecodeContext(c)
	if err != nil {
		return value, err
	}
	b, err := d.BytesField(MaximumAdmissionDeliveryBytes)
	if err != nil || d.Finish() != nil {
		return AdmissionDelivery{}, ErrAdmissionDelivery
	}
	value.Binding, err = DecodeAdmissionBinding(b)
	if err != nil {
		return value, err
	}
	again, err := value.CanonicalBytes()
	if err != nil || !bytes.Equal(again, raw) {
		return AdmissionDelivery{}, errors.Join(ErrAdmissionDelivery, err)
	}
	return value, nil
}

// AdmissionDeliveryReceipt is deterministic historical proof retention. There
// is deliberately no clock, expiry, current-head assertion or execution grant.
type AdmissionDeliveryReceipt struct {
	Version                                                 uint16
	DeliveryID, EnrollmentID, ContextID, ScopeID, BindingID types.Hash
	Role                                                    AdmissionDeliveryRole
	Signature                                               [64]byte
}

func (r AdmissionDeliveryReceipt) unsignedBytes() ([]byte, error) {
	if r.Version != Version2 || r.DeliveryID.IsZero() || r.EnrollmentID.IsZero() || r.ContextID.IsZero() || r.ScopeID.IsZero() || r.BindingID.IsZero() || (r.Role != AdmissionDeliveryAuthority && r.Role != AdmissionDeliveryTarget) {
		return nil, ErrAdmissionDelivery
	}
	out := codec.NewEncoder(AdmissionDeliveryReceiptBytes - ed25519.SignatureSize)
	out.Fixed([]byte("OMCVDAR2"))
	out.U16(r.Version)
	for _, id := range []types.Hash{r.DeliveryID, r.EnrollmentID, r.ContextID, r.ScopeID, r.BindingID} {
		out.Fixed(id[:])
	}
	out.U8(uint8(r.Role))
	return out.Bytes(), nil
}

func (r AdmissionDeliveryReceipt) CanonicalBytes() ([]byte, error) {
	raw, err := r.unsignedBytes()
	if err != nil {
		return nil, err
	}
	return append(raw, r.Signature[:]...), nil
}

func DecodeAdmissionDeliveryReceipt(raw []byte) (AdmissionDeliveryReceipt, error) {
	var r AdmissionDeliveryReceipt
	if len(raw) != AdmissionDeliveryReceiptBytes {
		return r, ErrAdmissionDelivery
	}
	d := codec.NewDecoder(raw)
	if !magic(d, "OMCVDAR2") {
		return r, ErrAdmissionDelivery
	}
	r.Version, _ = d.U16()
	for _, id := range []*types.Hash{&r.DeliveryID, &r.EnrollmentID, &r.ContextID, &r.ScopeID, &r.BindingID} {
		fixed(d, id[:])
	}
	role, _ := d.U8()
	r.Role = AdmissionDeliveryRole(role)
	fixed(d, r.Signature[:])
	again, err := r.CanonicalBytes()
	if err != nil || d.Finish() != nil || !bytes.Equal(again, raw) {
		return AdmissionDeliveryReceipt{}, ErrAdmissionDelivery
	}
	return r, nil
}

func (r AdmissionDeliveryReceipt) ID() (types.Hash, error) {
	raw, err := r.CanonicalBytes()
	if err != nil {
		return types.Hash{}, err
	}
	return types.DomainHash("OMESH/custody/v2/required/admission-delivery/receipt/id", raw), nil
}

func deliveryReceiptFor(d AdmissionDelivery) (AdmissionDeliveryReceipt, error) {
	did, err := d.ID()
	if err != nil {
		return AdmissionDeliveryReceipt{}, err
	}
	eid, err := d.Enrollment.ID()
	if err != nil {
		return AdmissionDeliveryReceipt{}, err
	}
	return AdmissionDeliveryReceipt{Version: Version2, DeliveryID: did, EnrollmentID: eid, ContextID: d.Enrollment.ContextID, ScopeID: d.Enrollment.ScopeID, BindingID: d.Enrollment.BindingID, Role: d.Enrollment.Role}, nil
}

// Sign derives every receipt field from the validated delivery rather than
// accepting caller-selected acknowledgements. The zero receipt is a valid
// constructor receiver; the returned signed value is the complete receipt.
func (AdmissionDeliveryReceipt) Sign(d AdmissionDelivery, key ed25519.PrivateKey) (AdmissionDeliveryReceipt, error) {
	if !validKey(key) || !bytes.Equal(key.Public().(ed25519.PublicKey), d.Enrollment.ReceiptPublicKey[:]) {
		return AdmissionDeliveryReceipt{}, ErrAdmissionDelivery
	}
	r, err := deliveryReceiptFor(d)
	if err != nil {
		return AdmissionDeliveryReceipt{}, err
	}
	raw, err := r.unsignedBytes()
	if err != nil {
		return AdmissionDeliveryReceipt{}, err
	}
	h := types.DomainHash("OMESH/custody/v2/required/admission-delivery/receipt/signature", raw)
	copy(r.Signature[:], ed25519.Sign(key, h[:]))
	return r, nil
}

func (r AdmissionDeliveryReceipt) Verify(d AdmissionDelivery) error {
	expected, err := deliveryReceiptFor(d)
	if err != nil {
		return err
	}
	raw, err := r.unsignedBytes()
	wanted, _ := expected.unsignedBytes()
	if err != nil || !bytes.Equal(raw, wanted) {
		return errors.Join(ErrAdmissionDelivery, err)
	}
	h := types.DomainHash("OMESH/custody/v2/required/admission-delivery/receipt/signature", raw)
	if !ed25519.Verify(d.Enrollment.ReceiptPublicKey[:], h[:], r.Signature[:]) {
		return ErrAdmissionDelivery
	}
	return nil
}
